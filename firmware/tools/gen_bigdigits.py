"""Generate src/bigdigits.cpp: Montserrat Bold digits and ':' as alpha bitmaps, for clock
numbers bigger than LVGL's built-in fonts (which stop at 48 px).

Usage: python tools/gen_bigdigits.py Montserrat-Bold.ttf
(Montserrat Bold: https://cdn.jsdelivr.net/fontsource/fonts/montserrat@latest/latin-700-normal.ttf)

Sizes are em sizes in panel pixels: the prototype's 412-unit sizes times 240/412.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

CHARS = "0123456789:"
SIZES = {"stack": round(176 * 240 / 412), "orbit": round(84 * 240 / 412)}

font_path = sys.argv[1]
out = os.path.join(os.path.dirname(__file__), "..", "src", "bigdigits.cpp")

lines = [
    "// Generated by tools/gen_bigdigits.py from Montserrat Bold (SIL Open Font License). Do not edit.",
    '#include "bigdigits.h"',
    "",
    "namespace bigdigits {",
    "",
]
sets = []
for name, px in SIZES.items():
    font = ImageFont.truetype(font_path, px)
    ascent, descent = font.getmetrics()
    glyphs = []
    for ch in CHARS:
        left, top, right, bottom = font.getbbox(ch, anchor="ls")  # relative to the baseline
        w, h = right - left, bottom - top
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
        data = img.tobytes()
        var = f"{name}_{CHARS.index(ch)}"
        lines.append(f"static const uint8_t {var}[] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        glyphs.append((ch, var, w, h, left, top, round(font.getlength(ch))))
    lines.append(f"static const Glyph {name}_glyphs[] = {{")
    for ch, var, w, h, left, top, adv in glyphs:
        lines.append(f"    {{'{ch}', {var}, {w}, {h}, {left}, {top}, {adv}}},")
    lines.append("};")
    lines.append("")
    # Vertical middle of the em box, as the prototype's canvas textBaseline = 'middle' uses.
    sets.append(f"const Font {name.upper()} = {{{name}_glyphs, {len(CHARS)}, {px}, {(ascent - descent) // 2}}};")
lines += sets + ["", "}  // namespace bigdigits", ""]
with open(out, "w", newline="\n") as f:
    f.write("\n".join(lines))
print("wrote", os.path.normpath(out))
